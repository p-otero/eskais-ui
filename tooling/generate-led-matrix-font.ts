function compose(letter: string, mark: Mark): Drawing {
  const body = squeezedCapitals[letter] ?? lowerBody(letter)
  const rows = [...mark, ...body]
  if (rows.length !== 7) throw new Error(`${letter} with a mark is ${String(rows.length)} rows, not 7`)
  return rows as unknown as Drawing
}

const base32 = "0123456789abcdefghijklmnopqrstuv"

function encode(drawing: Drawing) {
  return drawing
    .map((row) => {
      if (!/^[.#]{5}$/.test(row)) throw new Error(`"${row}" isn't five dots and hashes`)
      return base32[Number.parseInt(row.replaceAll(".", "0").replaceAll("#", "1"), 2)]
    })
    .join("")
}

function glyphs(): (readonly [string, Drawing])[] {
  const composed = Object.entries(accented).map(
    ([char, [letter, mark]]) => [char, compose(letter, marks[mark])] as const,
  )
  return [...Object.entries(ascii), ...Object.entries(symbols), ...composed].toSorted(
    ([a], [b]) => a.codePointAt(0)! - b.codePointAt(0)!,
  )
}

function fontModule() {
  const entries = glyphs().map(([char, drawing]) => `${char}${encode(drawing)}`)
  const lines: string[] = []
  for (let index = 0; index < entries.length; index += 12)
    lines.push(JSON.stringify(entries.slice(index, index + 12).join("")))
  return `const ledMatrixGlyphData = [
${lines.map((line) => `  ${line},`).join("\n")}
].join("")

export { ledMatrixGlyphData }
`
}

writeFileSync(resolve(import.meta.dirname, "..", "registry", "ui", "led-matrix-glyphs.ts"), fontModule())
